import fs from "node:fs";
import path from "node:path";
import { TAGS } from "./tags.mjs";

const root = process.argv[2];
if (!root) {
  console.error('Usage: node scripts/generateMeals.mjs "/path/to/Downloads"');
  process.exit(1);
}

const BASE = "https://res.cloudinary.com/w6mugeo5/image/upload/f_auto,q_auto,c_limit,w_1200";

// category value -> local folder name
const FOLDERS = {
  breakfast: "breakfast",
  lunch_dinner: "lunch_and_dinner",
  snacks: "snacks_and_fruits",
};

// Fix typos in the DISPLAY name only (the URL still uses the real file name)
const FIXES = {
  "hard-boilde-eggs-with-kachumbari-and-avocado": "hard-boiled-eggs-with-kachumbari-and-avocado",
  "white-rice-miced-meat-and-avocado": "white-rice-minced-meat-and-avocado",
  "bread-stuffed-with-cadburry-chocolate-and-tea": "bread-stuffed-with-cadbury-chocolate-and-tea",
  "yellowrice-chicken-and-potatoes": "yellow-rice-chicken-and-potatoes",
  "icecream": "ice-cream",
  "cocacola-and-cupcakes": "coca-cola-and-cupcakes",
};

const SMALL = new Set(["and", "or", "with", "of", "in", "the", "a", "to", "on"]);

function toDisplayName(slug) {
  const fixed = FIXES[slug] ?? slug;
  return fixed
    .split("-")
    .map((w, i) => (i > 0 && SMALL.has(w) ? w : w.charAt(0).toUpperCase() + w.slice(1)))
    .join(" ");
}

const meals = [];
const seen = new Map();
const slugsByCategory = Object.fromEntries(
  Object.keys(FOLDERS).map((c) => [c, new Set()])
);
let id = 1;

for (const [category, folder] of Object.entries(FOLDERS)) {
  const files = fs
    .readdirSync(path.join(root, folder))
    .filter((f) => /\.(jpe?g|png|webp)$/i.test(f))
    .sort();

  for (const file of files) {
    const slug = file.replace(/\.[^.]+$/, "");
    if (/\s/.test(file)) console.warn(`Spaces in file name: "${file}"`);
    if (/^\d+$/.test(slug)) console.warn(`Number-only file name: "${file}"`);
    if (seen.has(file)) console.warn(`Duplicate "${file}" in ${seen.get(file)} and ${category}`);
    seen.set(file, category);
    slugsByCategory[category].add(slug);

    meals.push({
      id: id++,
      name: toDisplayName(slug),
      category,
      image_url: `${BASE}/${encodeURIComponent(file)}`,
      tags: Object.keys(TAGS).filter((t) => TAGS[t][category]?.includes(slug)),
    });
  }
}

// catch typos in tags.mjs (a name that doesn't match a file in that category)
for (const [tag, byCategory] of Object.entries(TAGS)) {
  for (const [category, names] of Object.entries(byCategory)) {
    for (const name of names) {
      if (!slugsByCategory[category]?.has(name)) {
        console.warn(`Tag "${tag}" / ${category}: no file named "${name}"`);
      }
    }
  }
}

const output =
  "// Generated by scripts/generateMeals.mjs. Do not edit by hand.\n" +
  `export const meals = ${JSON.stringify(meals, null, 2)};\n`;

fs.writeFileSync(new URL("../src/data/meals.js", import.meta.url), output);
console.log(`Wrote ${meals.length} meals`);

// ---- also write server/db/seed.sql ----
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const tagNames = Object.keys(TAGS);

const lines = [
  "-- Generated by client/scripts/generateMeals.mjs. Do not edit by hand.",
  "BEGIN;",
];

if (tagNames.length) {
  lines.push(
    `INSERT INTO tags (name) VALUES ${tagNames.map((t) => `(${q(t)})`).join(", ")};`
  );
}

lines.push(
  "INSERT INTO meals (id, name, category, image_url) VALUES",
  meals
    .map((m) => `  (${m.id}, ${q(m.name)}, ${q(m.category)}, ${q(m.image_url)})`)
    .join(",\n") + ";"
);

const links = meals.flatMap((m) =>
  m.tags.map((t) => `  (${m.id}, (SELECT id FROM tags WHERE name = ${q(t)}))`)
);
if (links.length) {
  lines.push("INSERT INTO meal_tags (meal_id, tag_id) VALUES", links.join(",\n") + ";");
}

lines.push(
  "SELECT setval(pg_get_serial_sequence('meals', 'id'), (SELECT MAX(id) FROM meals));",
  "COMMIT;"
);

const dbDir = new URL("../../server/db/", import.meta.url);
fs.mkdirSync(dbDir, { recursive: true });
fs.writeFileSync(new URL("seed.sql", dbDir), lines.join("\n") + "\n");
console.log("Wrote server/db/seed.sql");